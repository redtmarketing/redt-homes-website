/**
 * redT Homes — .html → clean URL redirect generator (zero dependencies)
 *
 * Every page declares a clean canonical URL (e.g. /team/, /blog/some-post),
 * but Netlify also serves the raw file paths (/team/index.html,
 * /blog/some-post.html) with a 200. Google finds those copies and reports
 * them in Search Console as "Alternate page with proper canonical tag" and
 * "Duplicate, Google chose different canonical than user" (Nov 2026).
 *
 * This script writes `_redirects` with one forced 301 per page, from the
 * file path to that page's own canonical — but only when the canonical is
 * exactly the clean form of the same file (x.html → x, dir/index.html →
 * dir/), so a page can never be redirected somewhere else by mistake.
 * Rules are forced ("301!") because the .html file exists and would
 * otherwise shadow the rule. Netlify reads `_redirects` before the rules
 * in netlify.toml.
 *
 * Run with: node build-html-redirects.js (after build-listings.js /
 * build-blog.js / build-team.js, whenever pages are added or removed),
 * then deploy.
 */
const fs = require("fs");
const path = require("path");

const ROOT = __dirname;
const SITE_URL = "https://www.redthomes.com";
const SKIP_DIRS = new Set(["node_modules", ".git", "assets", "data", "website-working-files", ".netlify", ".claude"]);

function walk(dir, out = []) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    if (entry.name.startsWith("_") || SKIP_DIRS.has(entry.name)) continue;
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) walk(full, out);
    else if (entry.name.endsWith(".html")) out.push(full);
  }
  return out;
}

const rules = [];
const skipped = [];
for (const file of walk(ROOT).sort()) {
  const filePath = "/" + path.relative(ROOT, file).split(path.sep).join("/");
  const html = fs.readFileSync(file, "utf8");
  const m = html.match(/<link rel="canonical" href="([^"]+)"/);
  if (!m || !m[1].startsWith(SITE_URL)) {
    skipped.push(`${filePath} (no canonical)`);
    continue;
  }
  const canonical = m[1].slice(SITE_URL.length) || "/";
  const expected = filePath.endsWith("/index.html")
    ? filePath.slice(0, -"index.html".length)
    : filePath.slice(0, -".html".length);
  if (canonical !== expected) {
    skipped.push(`${filePath} (canonical ${canonical})`);
    continue;
  }
  rules.push(`${filePath}  ${canonical}  301!`);
}

const header = `# Generated by build-html-redirects.js — do not edit by hand.
# Sends raw .html file paths to each page's clean canonical URL.
`;
fs.writeFileSync(path.join(ROOT, "_redirects"), header + rules.join("\n") + "\n");
console.log(`Wrote _redirects (${rules.length} rules).`);
if (skipped.length) console.log("Skipped:\n  " + skipped.join("\n  "));
